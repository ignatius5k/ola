// Generates supabase/seed.sql and supabase/tests/database/seed.test.sql from src/data.js
// so database counts/IDs cannot drift from the prototype. Deterministic: same input,
// byte-identical output. Run: npm run db:seed:generate
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { collections, originalLedger, laterLedger } from '../src/data.js';

const NS = 'f3c1a0de-5a39-4b7e-9c11-0a1a00000039'; // fixed namespace for Database Foundation seed ids
const sha256 = v => createHash('sha256').update(v).digest('hex');

function uuidV5(name) {
  const ns = Buffer.from(NS.replace(/-/g, ''), 'hex');
  const h = createHash('sha1').update(ns).update(name).digest();
  h[6] = (h[6] & 0x0f) | 0x50; h[8] = (h[8] & 0x3f) | 0x80;
  const x = h.subarray(0, 16).toString('hex');
  return `${x.slice(0, 8)}-${x.slice(8, 12)}-${x.slice(12, 16)}-${x.slice(16, 20)}-${x.slice(20)}`;
}
const q = s => `'${String(s).replace(/'/g, "''")}'`;
const minor = (amount, label) => {
  const m = Math.round(amount * 100);
  if (Math.abs(amount * 100 - m) > 1e-6 || !Number.isSafeInteger(m)) throw new Error(`${label}: ${amount} is not an exact 2-decimal amount`);
  return m;
};
// Canonical hash input: fixed key order, UTC instant, amounts as minor-unit strings.
const sourceHash = o => sha256(JSON.stringify(o));
const utc = iso => new Date(iso).toISOString();

const SYSTEM_COL = 'synthetic-collections';
const SYSTEM_LED = 'synthetic-ledger';
const ws = uuidV5('workspace:ola-demo');
const fileHash = f => sha256(readFileSync(new URL(`../public/mock-data/${f}`, import.meta.url)));
const batches = {
  collections:   { id: uuidV5('batch:collections'),    kind: 'collection', system: SYSTEM_COL, sha: fileHash('collections.csv') },
  ledgerInitial: { id: uuidV5('batch:ledger-initial'), kind: 'ledger',     system: SYSTEM_LED, sha: fileHash('ledger-initial.csv') },
  ledgerLater:   { id: uuidV5('batch:ledger-later'),   kind: 'ledger',     system: SYSTEM_LED, sha: fileHash('ledger-later.csv') }
};

const colRows = collections.map(c => {
  const am = minor(c.amount, c.id);
  const hash = sourceHash({ system: SYSTEM_COL, id: c.id, reference: c.reference, counterparty: c.counterparty, amountMinor: String(am), currency: c.currency, recordedAt: utc(c.time), channel: c.channel });
  return { ...c, uuid: uuidV5(`collection:${c.id}`), caseId: uuidV5(`case:${c.id}`), am, hash };
});
const ledRow = (l, batch) => {
  const am = minor(l.amount, l.id), fee = minor(l.fee, l.id);
  const hash = sourceHash({ system: SYSTEM_LED, id: l.id, reference: l.reference, amountMinor: String(am), feeMinor: String(fee), currency: l.currency, recordedAt: utc(l.time), postingType: l.type });
  return { ...l, uuid: uuidV5(`ledger:${l.id}`), am, fee, hash, batch };
};
const ledRows = [...originalLedger.map(l => ledRow(l, batches.ledgerInitial)), ledRow(laterLedger, batches.ledgerLater)];

const out = [];
const w = s => out.push(s);
w('-- GENERATED by scripts/generate-seed.mjs from src/data.js (Database Foundation). Do not edit by hand.');
w('-- Clean-replay seed for `supabase db reset`. Synthetic data only.');
w('');
w('-- Authentication identities, profiles, and memberships are created by the trusted bootstrap script.');
w(`insert into public.workspaces (id, name, active_rule_version) values (${q(ws)}, 'Ola Demo', 'demo-1');`);
w('');
w('-- Import batches: seed origin => file_object_path is NULL (trusted records). The "later" ledger batch is');
w('-- seeded but intentionally unprocessed: no reconciliation run references it and no case points at its posting.');
w('insert into public.import_batches (id, workspace_id, source_system, origin, file_sha256, kind, status) values');
w(Object.values(batches).map(b => `  (${q(b.id)}, ${q(ws)}, ${q(b.system)}, 'seed', ${q(b.sha)}, ${q(b.kind)}, 'accepted')`).join(',\n') + ';');
w('');
w('insert into public.collections (id, workspace_id, import_batch_id, source_system, source_record_id, reference, counterparty, amount_minor, currency, recorded_at, channel, created_by, source_hash, raw_payload) values');
w(colRows.map(c => `  (${q(c.uuid)}, ${q(ws)}, ${q(batches.collections.id)}, ${q(SYSTEM_COL)}, ${q(c.id)}, ${q(c.reference)}, ${q(c.counterparty)}, ${c.am}, ${q(c.currency)}, ${q(c.time)}, ${q(c.channel)}, null, ${q(c.hash)}, ${q(JSON.stringify(c))}::jsonb)`).join(',\n') + ';');
w('');
w('insert into public.ledger_postings (id, workspace_id, import_batch_id, source_system, source_record_id, reference, amount_minor, currency, recorded_at, created_by, source_hash, raw_payload, posting_type, fee_minor) values');
w(ledRows.map(l => `  (${q(l.uuid)}, ${q(ws)}, ${q(l.batch.id)}, ${q(SYSTEM_LED)}, ${q(l.id)}, ${q(l.reference)}, ${l.am}, ${q(l.currency)}, ${q(l.time)}, null, ${q(l.hash)}, ${q(JSON.stringify(l))}::jsonb, ${q(l.type)}, ${l.fee})`).join(',\n') + ';');
w('');
w('-- One case per collection. creator_id is NULL: trusted synthetic/system creation. Category/status are set by reconciliation (SCRUM-42).');
w('insert into public.cases (id, workspace_id, collection_id, workflow_status, creator_id) values');
w(colRows.map(c => `  (${q(c.caseId)}, ${q(ws)}, ${q(c.uuid)}, 'new', null)`).join(',\n') + ';');
w('');
w('-- Append-only audit trail via the primitive (system actor).');
for (const [k, b] of Object.entries(batches)) {
  w(`do $$ begin perform app.append_audit(${q(ws)}, 'import_batch.accepted', 'system', null, p_import_batch_id => ${q(b.id)}, p_payload => ${q(JSON.stringify({ origin: 'seed', batch: k, kind: b.kind }))}::jsonb); end $$;`);
}
const list = rows => `array[${rows.map(r => q(r.id)).join(', ')}]::text[]`;
const t = [];
t.push('-- GENERATED by scripts/generate-seed.mjs from src/data.js (Database Foundation). Do not edit by hand.');
t.push('-- Acceptance: source counts and IDs match src/data.js after migrations + seed; all FKs validated.');
t.push('begin;');
t.push('select plan(10);');
t.push(`select is((select count(*) from public.collections where workspace_id = ${q(ws)}), ${colRows.length}::bigint, 'collection count matches src/data.js');`);
t.push(`select is((select count(*) from public.ledger_postings where workspace_id = ${q(ws)}), ${ledRows.length}::bigint, 'ledger count matches src/data.js (initial + later)');`);
t.push(`select is((select array_agg(source_record_id order by source_record_id) from public.collections), (select array_agg(x order by x) from unnest(${list(colRows)}) x), 'collection source IDs match');`);
t.push(`select is((select array_agg(source_record_id order by source_record_id) from public.ledger_postings), (select array_agg(x order by x) from unnest(${list(ledRows)}) x), 'ledger source IDs match');`);
t.push(`select is((select count(*) from public.cases), ${colRows.length}::bigint, 'one case per collection');`);
t.push(`select is((select count(*) from public.ledger_postings p join public.import_batches b on b.id = p.import_batch_id and b.workspace_id = p.workspace_id where b.id = ${q(batches.ledgerLater.id)}), 1::bigint, 'later ledger batch holds exactly LED-5009');`);
t.push(`select is((select count(*) from public.ledger_allocations) + (select count(*) from public.reconciliation_runs), 0::bigint, 'later evidence is unprocessed: no runs, no allocations');`);
t.push(`select is((select count(*) from public.ledger_postings where reference = 'QR-241024-102'), 2::bigint, 'duplicate-reference scenario: two postings share QR-241024-102 with distinct source IDs');`);
t.push("select is((select count(*) from public.collections where source_hash <> raw_payload->>'hash') + (select count(*) from public.ledger_postings where source_hash <> raw_payload->>'hash'), 0::bigint, 'stored source hashes match generated payload hashes');");
t.push(`select is((select count(*) from pg_constraint where connamespace = 'public'::regnamespace and contype = 'f' and not convalidated), 0::bigint, 'all foreign keys validated');`);
t.push('select * from finish();');
t.push('rollback;');

const seedUrl = new URL('../supabase/seed.sql', import.meta.url);
const testUrl = new URL('../supabase/tests/database/seed.test.sql', import.meta.url);
const seedText = out.join('\n') + '\n';
const testText = t.join('\n') + '\n';
const checkOnly = process.argv.includes('--check');
const printSeed = process.argv.includes('--print-seed');

if (printSeed) {
  process.stdout.write(seedText);
} else if (checkOnly) {
  const checks = [
    [seedUrl, seedText, 'supabase/seed.sql'],
    [testUrl, testText, 'supabase/tests/database/seed.test.sql']
  ];

  for (const [url, expected, label] of checks) {
    if (readFileSync(url, 'utf8') !== expected) {
      throw new Error(`${label} is stale; run npm run db:seed:generate`);
    }
  }

  console.log('seed files match the deterministic generator');
} else {
  mkdirSync(new URL('../supabase/tests/database/', import.meta.url), { recursive: true });
  writeFileSync(seedUrl, seedText, 'utf8');
  writeFileSync(testUrl, testText, 'utf8');
  console.log(`seed: ${colRows.length} collections, ${ledRows.length} ledger postings, ${colRows.length} cases`);
}
